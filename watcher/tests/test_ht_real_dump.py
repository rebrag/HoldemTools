"""The adapter against REAL `engine dump-streets` output.

Every other htsolver test here feeds ht_bundles hand-written street documents
(ht_fakes.py), which pins the adapter against what we BELIEVE the engine
writes. This one feeds it what the engine actually wrote: a committed dump of
a tiny flop solve (three streets: the flop, one turn, one river), generated by
the commands at the top of engine/configs/fixtures/tiny_flop.json. No engine
runs in the test; the dump is data.

Two layers:
  - invariants a correct schema-4 street bundle must satisfy whatever the
    numbers are (strategies sum to 1 over held hands, equities are
    probabilities, an all-in and call is where the hand ends, ...);
  - a golden of the three bundles, so any drift in the adapter or in
    extraction.py's builders on engine-shaped input shows up as a diff.

Rewrite the golden after an intended change:
    python tests/test_ht_real_dump.py --write-golden
"""

import json
import os
import sys

import pytest

HERE = os.path.dirname(os.path.abspath(__file__))
if os.path.dirname(HERE) not in sys.path:
    sys.path.insert(0, os.path.dirname(HERE))

import extraction  # noqa: E402
import ht_bundles  # noqa: E402
from ht_bundles import CANONICAL_HANDS  # noqa: E402

DUMP_DIR = os.path.join(HERE, "fixtures", "tiny_flop_dump")
GOLDEN = os.path.join(HERE, "fixtures", "tiny_flop_golden.json")
FLOP, TURN, RIVER = "r:0", "r:0:c:c:2c", "r:0:c:c:2c:c:c:3d"
BLOB_PATH = "gametrees/2026/11/16/u/folder=3BB_3BTN/101500_line=F-R-C_pos=BB_icm=0.json"


def _load():
    with open(os.path.join(DUMP_DIR, "streets.json"), "r", encoding="utf-8") as f:
        dump = json.load(f)
    return dump, ht_bundles.extract_from_dump(dump, DUMP_DIR)


def _bundles():
    """The three street bundles, built exactly as the worker builds them."""
    _dump, extract = _load()
    ctx = extraction.build_board_context(
        board="QhJhTh", cfr_file="", src_gametree_path=BLOB_PATH, base_prefix="gametrees",
        stats=extract["results"], tree_info=extract["tree_info"],
        alive_positions=["BB", "BTN"], acting_pos="BB", chip_scale=1, hand_bb=100,
    )
    out = {}
    for seed, walk in extract["streets"].items():
        out[seed] = extraction.build_street_bundle(
            seed, walk["views"], walk["nodes_meta"], ctx, CANONICAL_HANDS)
    return out


def _stable(bundles):
    """Bundles without the fields that are a clock reading."""
    out = {}
    for seed, bundle in bundles.items():
        b = dict(bundle)
        b.pop("created_utc", None)
        out[seed] = b
    return out


# ------------------------------------------------------------- the dump


def test_the_dump_is_the_three_streets_the_fixture_promises():
    dump, extract = _load()
    assert [s["seed"] for s in dump["streets"]] == [FLOP, TURN, RIVER]
    assert [s["street"] for s in dump["streets"]] == ["flop", "turn", "river"]
    assert set(extract["streets"]) == {FLOP, TURN, RIVER}
    # The hand dictionary is the solve's compact universe; every name must
    # land on the canonical 1326 order or a whole column would be misplaced.
    positions = ht_bundles.canonical_positions(dump["hands"])
    assert len(set(positions)) == len(dump["hands"])
    assert [CANONICAL_HANDS[p] for p in positions] == dump["hands"]


def test_metadata_carries_what_the_worker_reads():
    dump, extract = _load()
    meta = dump["metadata"]
    # require_converged, engine_block and solve.json all read these keys.
    assert meta["solver_version"] and meta["engine_build"]
    assert isinstance(meta["iterations"], int) and meta["iterations"] > 0
    assert meta["pot"] == 100 and meta["effective_stack"] == 300
    assert len(meta["ev_chips"]) == 2
    assert "solved" in meta
    # Root EVs sum to the root pot (Pio's convention), and Pio's
    # "exploitable for" is half of nashconv.
    assert sum(meta["ev_chips"]) == pytest.approx(100, abs=1e-3)
    assert extract["results"]["exploitable"] == pytest.approx(meta["final_nashconv"] / 2)
    block = ht_bundles.engine_block(meta, watcher_id="w")
    assert block["solver"] == "htsolver" and block["build"] == meta["engine_build"]


# ----------------------------------------------------------- navigation


def test_an_allin_and_call_ends_the_hand_and_a_deal_opens_a_picker():
    meta = _bundles()[FLOP]["meta"]
    assert meta["r.0"]["type"] == "OOP_DEC"
    assert meta["r.0.c"]["type"] == "IP_DEC"
    # Check-check and bet-call go to the turn: the viewer offers the cards.
    assert meta["r.0.c.c"]["type"] == "SPLIT_NODE"
    assert meta["r.0.b50.c"]["type"] == "SPLIT_NODE"
    # Jam and call: no decision is left on any street, so no card picker.
    assert meta["r.0.b50.b300.c"] == {"type": "terminal"}
    assert meta["r.0.c.b50.b300.c"] == {"type": "terminal"}
    assert meta["r.0.b50.f"] == {"type": "terminal"}


def test_river_showdowns_are_terminal_and_children_resolve():
    bundle = _bundles()[RIVER]
    meta = bundle["meta"]
    root = "r.0.c.c.2c.c.c.3d"
    assert meta[root]["type"] == "OOP_DEC"
    assert meta[root + ".c.c"] == {"type": "terminal"}
    # Every action of every decision node leads somewhere the walk knows.
    for suffix, node in bundle["nodes"].items():
        for label, child in node["children"].items():
            assert extraction.node_id_to_suffix(child) in meta, (suffix, label)


def test_pot_triple_is_commitments_then_the_root_pot():
    bundles = _bundles()
    assert bundles[FLOP]["nodes"]["r.0"]["pot"] == [0, 0, 100]
    # Facing a 50 bet on the flop: the bettor has 50 in, the third element is
    # still the pot at the ROOT, which is what manifest.pot_chips is read from.
    assert bundles[FLOP]["nodes"]["r.0.b50"]["pot"] == [50, 0, 100]


# -------------------------------------------------------------- numbers


@pytest.mark.parametrize("seed", [FLOP, TURN, RIVER])
def test_every_held_hand_plays_a_full_strategy(seed):
    bundle = _bundles()[seed]
    seen = 0
    for suffix, node in bundle["nodes"].items():
        combos = node["combos"]
        # A node the actor never reaches has no combo block at all (this
        # solve is lopsided - the big blind never leads - so several lines
        # are off-path): no held combos, nothing to play. Same as a Pio
        # bundle, whose builder this is.
        if combos is None or combos[combos["actor"]] is None:
            continue
        scale = combos["scale"]["s"]
        rows = combos["strategy"]
        actor = combos[combos["actor"]]
        assert len(combos["actions"]) == len(node["children"])
        seen += 1
        assert len(rows) == len(combos["actions"])
        assert all(len(row) == len(actor["idx"]) for row in rows)
        for k in range(len(actor["idx"])):
            total = sum(row[k] for row in rows) / scale
            # Fixed-point per mille per action: allow a unit of rounding each.
            assert total == pytest.approx(1.0, abs=len(rows) / scale), (suffix, k)
    # The street's own root is always reached by its actor.
    assert seen >= 1
    root = bundle["nodes"][bundle["seed_suffix"]]
    assert root["combos"][root["combos"]["actor"]] is not None


@pytest.mark.parametrize("seed", [FLOP, TURN, RIVER])
def test_equity_is_a_probability_for_both_seats(seed):
    measured = 0
    for suffix, node in _bundles()[seed]["nodes"].items():
        combos = node["combos"]
        if combos is None:
            continue
        for seat, other in (("oop", "ip"), ("ip", "oop")):
            block = combos[seat]
            if block is None:
                continue  # the seat holds nothing at an off-path node
            assert block["idx"] == sorted(block["idx"])
            assert len(block["eq"]) == len(block["idx"]) == len(block["w"])
            for e in block["eq"]:
                assert e is None or 0 <= e <= combos["scale"]["eq"], (suffix, seat)
            assert node["seat_stats"][seat]["combos"] > 0
            if combos[other] is None:
                # Nobody to be measured against: the engine writes null, never
                # a 0 that would read as "this hand always loses".
                assert all(e is None for e in block["eq"]), (suffix, seat)
                assert node["seat_stats"][seat]["equity"] is None
            else:
                assert any(e is not None for e in block["eq"]), (suffix, seat)
                assert 0.0 <= node["seat_stats"][seat]["equity"] <= 1.0
                measured += 1
    assert measured >= 2  # both seats, at the street's root at least


def test_the_nuts_have_equity_one_wherever_they_are_held():
    # AhKh is a royal flush on Qh Jh Th from the flop on: whatever comes and
    # whatever the opponent holds, its equity is exactly 1. The button holds
    # it (AKs); a column shifted by one hand would put some other number here.
    checked = 0
    for bundle in _bundles().values():
        for node in bundle["nodes"].values():
            ip = (node["combos"] or {}).get("ip")
            if ip is None:
                continue
            by_hand = {CANONICAL_HANDS[i]: k for k, i in enumerate(ip["idx"])}
            if "AhKh" in by_hand and ip["eq"][by_hand["AhKh"]] is not None:
                assert ip["eq"][by_hand["AhKh"]] == node["combos"]["scale"]["eq"]
                checked += 1
    assert checked >= 3  # at least once on each street


def test_root_seat_evs_agree_with_the_solve():
    dump, _ = _load()
    stats = _bundles()[FLOP]["nodes"]["r.0"]["seat_stats"]
    # seat_stats is a reach-weighted mean over combos (no matchup weighting),
    # so it tracks the solve's root EV without equalling it.
    assert stats["oop"]["ev"] == pytest.approx(dump["metadata"]["ev_chips"][0], abs=15)
    assert stats["ip"]["ev"] == pytest.approx(dump["metadata"]["ev_chips"][1], abs=15)
    assert _bundles()[FLOP]["nodes"]["r.0"]["global_freq"] == pytest.approx(1.0)


# --------------------------------------------------------------- golden


def test_bundles_match_the_golden():
    with open(GOLDEN, "r", encoding="utf-8") as f:
        golden = json.load(f)
    actual = json.loads(json.dumps(_stable(_bundles())))
    assert sorted(actual) == sorted(golden)
    for seed in golden:
        assert actual[seed] == golden[seed], f"street {seed} drifted from the golden"


if __name__ == "__main__":
    if "--write-golden" in sys.argv:
        with open(GOLDEN, "w", encoding="utf-8", newline="\n") as f:
            json.dump(_stable(_bundles()), f, sort_keys=True, separators=(",", ":"))
            f.write("\n")
        print(f"wrote {GOLDEN} ({os.path.getsize(GOLDEN)} bytes)")
    else:
        sys.exit(pytest.main([__file__, "-q"]))
